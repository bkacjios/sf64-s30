#!/usr/bin/env python3
"""Segment symbols for the PocketGo S30 build (Makefile.s30).

The N64 link defines <segment>_ROM_START/_ROM_END and friends, which the game
uses to load overlays and asset segments. On the S30, overlays are linked into
the executable and asset segments are files mapped at their VRAM
(tools/s30/make_assets.py), so:

- segments.ld: every segment's ROM range from the yamls (the game only compares
  and passes these around; src/s30/ultra.c finds a segment by its ROM start),
  and for each overlay its data and bss bounds: Makefile.s30 puts each
  overlay's .data and .bss in sections of their own (ovl_<name>_data,
  ovl_<name>_bss), so that loading an overlay can reset them.
- segtab.c: the asset segments (ROM start, VRAM, name) and the overlays (ROM
  start, data and bss bounds, and a copy of the data to reset from), for
  src/s30/ultra.c.
"""

import re
import sys

YAMLS = ["yamls/us/rev1/main.yaml", "yamls/us/rev1/assets.yaml", "yamls/us/rev1/overlays.yaml"]
OUT = "build_s30"


def parse():
    segs = []  # (name, rom start, vram, kind, dir)
    end = None
    for path in YAMLS:
        cur = None
        for line in open(path):
            m = re.match(r"  - name: (\w+)", line)
            if m:
                cur = {"name": m.group(1), "start": None, "vram": None, "type": None, "dir": ""}
                segs.append(cur)
                continue
            m = re.match(r"  - \[(0x[0-9A-Fa-f]+)\]\s*$", line)
            if m:
                end = int(m.group(1), 16)
            if cur is None:
                continue
            for key in ("start", "vram"):
                m = re.match(rf"    {key}: (0x[0-9A-Fa-f]+)", line)
                if m:
                    cur[key] = int(m.group(1), 16)
            m = re.match(r"    type: (\w+)", line)
            if m:
                cur["type"] = m.group(1)
            m = re.match(r"    dir: (\S+)", line)
            if m:
                cur["dir"] = m.group(1)
    segs = [s for s in segs if s["start"] is not None]
    segs.sort(key=lambda s: s["start"])
    for i, s in enumerate(segs):
        s["end"] = segs[i + 1]["start"] if i + 1 < len(segs) else end
    return segs


def main():
    segs = parse()
    assets = [s for s in segs if s["dir"] == "assets"]
    overlays = [s for s in segs if s["dir"].startswith("overlays/")]
    with open(f"{OUT}/segments.ld", "w") as f:
        f.write("/* Generated by tools/s30/make_segments.py. Do not edit. */\n")
        for s in segs:
            n = s["name"]
            f.write(f"{n}_ROM_START = 0x{s['start']:08X};\n{n}_ROM_END = 0x{s['end']:08X};\n")
            if s["vram"] is not None and s not in overlays:
                f.write(f"{n}_VRAM = 0x{s['vram']:08X};\n")
        for s in overlays:
            n = s["name"]
            f.write(f"{n}_DATA_START = __start_{n}_data;\n{n}_RODATA_END = __stop_{n}_data;\n"
                    f"{n}_BSS_START = __start_{n}_bss;\n{n}_BSS_END = __stop_{n}_bss;\n"
                    f"{n}_TEXT_START = 0;\n{n}_TEXT_END = 0;\n{n}_VRAM = 0;\n{n}_VRAM_END = 0;\n")
    with open(f"{OUT}/segtab.c", "w") as f:
        f.write("/* Generated by tools/s30/make_segments.py. Do not edit. */\n"
                "#include <stddef.h>\n#include \"s30_platform.h\"\n\n")
        for s in overlays:
            n = s["name"]
            f.write(f"extern unsigned char __start_{n}_data[], __stop_{n}_data[], "
                    f"__start_{n}_bss[], __stop_{n}_bss[];\n")
        f.write("\nconst S30AssetSegment gS30AssetSegments[] = {\n")
        for s in assets:
            f.write(f"    {{ 0x{s['start']:08X}, 0x{s['vram']:08X}, \"{s['name']}\" }},\n")
        f.write(f"}};\nconst int gS30AssetSegmentCount = {len(assets)};\n\nS30Overlay gS30Overlays[] = {{\n")
        for s in overlays:
            n = s["name"]
            f.write(f"    {{ 0x{s['start']:08X}, __start_{n}_data, __stop_{n}_data, "
                    f"__start_{n}_bss, __stop_{n}_bss, NULL }},\n")
        f.write(f"}};\nconst int gS30OverlayCount = {len(overlays)};\n")
    print(f"{len(segs)} segments: {len(assets)} asset segments, {len(overlays)} overlays")


if __name__ == "__main__":
    main()
