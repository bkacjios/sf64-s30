#!/usr/bin/env python3
"""Build the asset segments for the PocketGo S30 build (Makefile.s30 assets).

Each asset segment in yamls/us/rev1/assets.yaml (src/assets/<name>/<name>.c,
from Torch) is compiled for ARM and linked at its N64 VRAM (0x0N000000 for a
segment, or its RAM address). The game loads a segment by mapping
data/<name>.bin at that address (src/s30/ultra.c), so segmented addresses work
as plain pointers.

Outputs, in build_s30/assets:
- data/<name>.bin: the segment's bytes (.data, .rodata and .bss)
- symbols.ld: every asset symbol's address, for the game's link
- textab.c: per segment, the texture arrays whose elements aren't 16-bit,
  with their element size: the renderer reads texture memory by element (assets are
  compiled little-endian, so a u8 array keeps the N64's byte order and a u16
  or u32 array doesn't), and a 16-bit texture load can't tell them apart.
"""

import os
import re
import subprocess
import sys

TARGET_CFLAGS = [
    "-marm", "-march=armv7-a", "-mfpu=neon-vfpv4", "-mfloat-abi=hard", "-fno-short-enums",
    "-isystem", os.environ["S30_SYSROOT"] + "/usr/include",
    "-std=gnu11", "-O0", "-fno-common", "-fno-toplevel-reorder", "-fno-zero-initialized-in-bss",
    "-DVERSION_US=1", "-D_MIPS_SZLONG=32", "-DF3DEX_GBI", "-DNDEBUG", "-D_LANGUAGE_C", "-DLANGUAGE_C", "-DNON_MATCHING",
    "-DTARGET_S30", "-Iinclude", "-Ibin/us.rev1", "-I.",
]
OUT = "build_s30/assets"
YAML = "yamls/us/rev1/assets.yaml"
ARRAY = re.compile(r"^(?:static )?(?:const )?(u8|s8|char|u16|s16|u32|s32|u64)\s+(\w+)\[")
ELEM = {"u8": 1, "s8": 1, "char": 1, "u16": 2, "s16": 2, "u32": 4, "s32": 4, "u64": 8}


def segments():
    name = vram = kind = None
    for line in open(YAML):
        m = re.match(r"\s*- name: (\w+)", line)
        if m:
            name, vram, kind = m.group(1), None, None
        m = re.match(r"\s*type: (\w+)", line)
        if m:
            kind = m.group(1)
        m = re.match(r"\s*vram: (0x[0-9A-Fa-f]+)", line)
        if m and name and kind == "code" and os.path.exists(f"src/assets/{name}/{name}.c"):
            yield name, int(m.group(1), 16)


def run(cmd):
    r = subprocess.run(cmd, capture_output=True, text=True)
    if r.returncode != 0:
        sys.exit(f"{' '.join(cmd)}\n{r.stdout}{r.stderr}")
    return r.stdout


def link(name, vram, extra=()):
    obj, elf, ld = f"{OUT}/{name}.o", f"{OUT}/{name}.elf", f"{OUT}/{name}.ld"
    with open(ld, "w") as f:
        f.write(f"SECTIONS {{\n  . = 0x{vram:08X};\n"
                "  .data : { *(.data*) *(.rodata*) *(.bss*) *(COMMON) }\n"
                "  /DISCARD/ : { *(.comment) *(.ARM.attributes) *(.note*) }\n}\n")
    run(["arm-none-eabi-ld", "-T", ld, *extra, obj, "-o", elf])
    sizes = {}
    for line in run(["arm-none-eabi-nm", "-S", "--defined-only", elf]).splitlines():
        parts = line.split()
        if len(parts) == 4 and parts[2] in "dDbBrR":
            sizes[parts[3]] = (int(parts[0], 16), int(parts[1], 16))
    return sizes


def main():
    os.makedirs(f"{OUT}/data", exist_ok=True)
    segs = list(segments())
    symbols = {}
    owner = {}
    # Pass 1: each segment's own symbols (references to other segments left
    # unresolved)
    for name, vram in segs:
        run(["arm-none-eabi-gcc", *TARGET_CFLAGS, "-c", f"src/assets/{name}/{name}.c", "-o", f"{OUT}/{name}.o"])
        for sym, (addr, _) in link(name, vram, ["--unresolved-symbols=ignore-all"]).items():
            if sym in symbols and symbols[sym] != addr:
                print(f"warning: {sym} in {owner[sym]} and {name}, kept the first", file=sys.stderr)
                continue
            symbols[sym] = addr
            owner[sym] = name
    # Pass 2: linked with the other segments' symbols
    textures = {}  # segment name: [(address, size, element size)]
    for name, vram in segs:
        ext = f"{OUT}/{name}.ext.ld"
        with open(ext, "w") as f:
            for sym, addr in symbols.items():
                if owner[sym] != name:
                    f.write(f"{sym} = 0x{addr:08X};\n")
        sizes = link(name, vram, [ext])
        run(["arm-none-eabi-objcopy", "-O", "binary", "-j", ".data", f"{OUT}/{name}.elf", f"{OUT}/data/{name}.bin"])
        for line in open(f"src/assets/{name}/{name}.c"):
            m = ARRAY.match(line)
            if m and m.group(2) in sizes and ELEM[m.group(1)] != 2:
                addr, size = sizes[m.group(2)]
                textures.setdefault(name, []).append((addr, size, ELEM[m.group(1)]))
        print(f"{name}: 0x{vram:08X}, {os.path.getsize(f'{OUT}/data/{name}.bin')} bytes")

    with open(f"{OUT}/symbols.ld", "w") as f:
        for sym, addr in sorted(symbols.items()):
            f.write(f"{sym} = 0x{addr:08X};\n")
    with open(f"{OUT}/textab.c", "w") as f:
        f.write("/* Generated by tools/s30/make_assets.py. Do not edit. */\n"
                "#include <stddef.h>\n#include \"s30_platform.h\"\n\n")
        for name in sorted(textures):
            f.write(f"static const S30TexRange sTex_{name}[] = {{\n")
            for addr, size, elem in sorted(textures[name]):
                f.write(f"    {{ 0x{addr:08X}, 0x{addr + size:08X}, {elem} }},\n")
            f.write("};\n")
        f.write("\nconst S30SegTex gS30SegTex[] = {\n")
        for name in sorted(textures):
            f.write(f"    {{ \"{name}\", sTex_{name}, {len(textures[name])} }},\n")
        f.write(f"}};\nconst int gS30SegTexCount = {len(textures)};\n")

if __name__ == "__main__":
    main()
